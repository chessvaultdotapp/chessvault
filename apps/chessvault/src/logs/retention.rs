use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use chrono::{DateTime, Days, FixedOffset, Utc};

use super::LOG_TIMESTAMP_FORMAT;

const MAX_LOG_FILES: usize = 20;
const RETENTION_DAYS: u64 = 7;

pub(super) fn start(current_log: PathBuf) {
    if let Err(error) = std::thread::Builder::new()
        .name("log-cleanup".into())
        .spawn(move || run_cleanup(&current_log, Utc::now().fixed_offset()))
    {
        tracing::error!(%error, "Failed to start log cleanup thread");
    }
}

fn run_cleanup(current_log: &Path, now: DateTime<FixedOffset>) {
    if let Err(error) = cleanup(current_log, now) {
        tracing::error!(error = %format!("{error:#}"), "Log cleanup failed");
    }
}

// Only accept the exact filename format generated by this application.
fn log_timestamp(path: &Path) -> Option<DateTime<FixedOffset>> {
    let name = path.file_name()?.to_str()?;
    let timestamp = name.strip_suffix(".log")?;
    let parsed = DateTime::parse_from_str(timestamp, LOG_TIMESTAMP_FORMAT).ok()?;
    (parsed.format(LOG_TIMESTAMP_FORMAT).to_string() == timestamp).then_some(parsed)
}

fn cleanup(current_log: &Path, now: DateTime<FixedOffset>) -> Result<()> {
    let directory = current_log.parent().context("Log file has no parent directory")?;
    let entries =
        fs::read_dir(directory).with_context(|| format!("Failed to read log directory {}", directory.display()))?;
    let mut candidates = Vec::new();
    for entry in entries {
        let result = (|| -> Result<_> {
            let entry = entry.context("Failed to read log directory entry")?;
            let path = entry.path();
            if path == current_log {
                return Ok(None);
            }
            let Some(timestamp) = log_timestamp(&path) else {
                return Ok(None);
            };
            let file_type = entry
                .file_type()
                .with_context(|| format!("Failed to inspect {}", path.display()))?;
            // Never follow symlinks or remove directories, even with matching names.
            Ok(file_type.is_file().then_some((timestamp, path)))
        })();
        match result {
            Ok(Some(candidate)) => candidates.push(candidate),
            Ok(None) => {}
            Err(error) => tracing::error!(error = %format!("{error:#}"), "Log cleanup failed"),
        }
    }
    candidates.sort_by(|left, right| right.cmp(left));
    let cutoff = now
        .checked_sub_days(Days::new(RETENTION_DAYS))
        .context("Invalid log retention cutoff")?;
    // Reserve one slot for the active log, regardless of its age or filename ordering.
    let mut retained = 1;
    for (timestamp, path) in candidates {
        if timestamp < cutoff || retained >= MAX_LOG_FILES {
            if let Err(error) = fs::remove_file(&path) {
                tracing::error!(%error, path = %path.display(), "Failed to delete old log file");
            }
        } else {
            retained += 1;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::logs::Logs;
    use std::sync::atomic::{AtomicUsize, Ordering};
    use tracing_subscriber::layer::SubscriberExt;

    struct TestDir(PathBuf);

    impl TestDir {
        fn new() -> Self {
            static NEXT: AtomicUsize = AtomicUsize::new(0);
            let path = std::env::temp_dir().join(format!(
                "chessvault-log-retention-{}-{}-{}",
                std::process::id(),
                Utc::now().timestamp_nanos_opt().unwrap(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
            fs::create_dir(&path).unwrap();
            Self(path)
        }

        fn log(&self, timestamp: DateTime<FixedOffset>) -> PathBuf {
            let path = self.0.join(format!("{}.log", timestamp.format(LOG_TIMESTAMP_FORMAT)));
            fs::write(&path, "test log").unwrap();
            path
        }
    }

    impl Drop for TestDir {
        fn drop(&mut self) {
            fs::remove_dir_all(&self.0).unwrap();
        }
    }

    fn now() -> DateTime<FixedOffset> {
        DateTime::parse_from_rfc3339("2026-06-20T12:00:00+00:00").unwrap()
    }

    #[test]
    fn newly_opened_log_is_recognized_and_protected() {
        let dir = TestDir::new();
        let (file, error) = crate::logs::prepare_file_logging(Ok(dir.0.clone()));
        assert!(error.is_none());
        let file = file.unwrap();
        assert!(file.path.is_file());
        let timestamp = log_timestamp(&file.path).unwrap();
        cleanup(&file.path, timestamp + chrono::Duration::days(30)).unwrap();
        assert!(file.path.exists());
        drop(file);
    }

    #[test]
    fn count_limit_includes_current_log_and_keeps_newest() {
        let dir = TestDir::new();
        let current = dir.log(now());
        let paths: Vec<_> = (1..=25)
            .map(|hours| dir.log(now() - chrono::Duration::hours(hours)))
            .collect();
        cleanup(&current, now()).unwrap();
        assert!(current.exists());
        for (index, path) in paths.iter().enumerate() {
            assert_eq!(path.exists(), index < MAX_LOG_FILES - 1);
        }
    }

    #[test]
    fn age_limit_preserves_boundary_and_current_even_when_old() {
        let dir = TestDir::new();
        let current = dir.log(now() - chrono::Duration::days(30));
        let boundary = dir.log(now() - chrono::Duration::days(7));
        let old = dir.log(now() - chrono::Duration::days(7) - chrono::Duration::nanoseconds(1));
        let recent = dir.log(now() - chrono::Duration::days(1));
        cleanup(&current, now()).unwrap();
        assert!(current.exists());
        assert!(boundary.exists());
        assert!(recent.exists());
        assert!(!old.exists());
    }

    #[test]
    fn unrelated_files_and_matching_directories_are_untouched() {
        let dir = TestDir::new();
        let current = dir.log(now());
        for name in [
            "notes.log",
            "2026-01-01.log",
            "2026-01-01T00-00-00-000000000+0000.log.bak",
        ] {
            fs::write(dir.0.join(name), "keep").unwrap();
        }
        let directory = dir.0.join("2026-01-01T00-00-00-000000000+0000.log");
        fs::create_dir(&directory).unwrap();
        cleanup(&current, now()).unwrap();
        assert_eq!(fs::read_dir(&dir.0).unwrap().count(), 5);
    }

    #[cfg(unix)]
    #[test]
    fn matching_symlinks_are_untouched() {
        let dir = TestDir::new();
        let current = dir.log(now());
        let target = dir.0.join("keep.txt");
        fs::write(&target, "keep").unwrap();
        let link = dir.0.join("2026-01-01T00-00-00-000000000+0000.log");
        std::os::unix::fs::symlink(&target, &link).unwrap();
        cleanup(&current, now()).unwrap();
        assert!(link.symlink_metadata().unwrap().file_type().is_symlink());
        assert!(target.exists());
    }

    #[test]
    fn missing_directory_is_reported_at_error_level_without_panicking() {
        let dir = TestDir::new();
        let logs = Logs::default();
        let subscriber = tracing_subscriber::registry().with(logs.capture_layer());
        tracing::subscriber::with_default(subscriber, || {
            run_cleanup(&dir.0.join("missing/current.log"), now());
        });
        let snapshot = logs.snapshot();
        assert!(snapshot.contains("ERROR"));
        assert!(snapshot.contains("Failed to read log directory"));
    }
}
